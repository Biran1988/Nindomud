SHORTCUT_JUTSU = {short: key for key, short in JUTSU_SHORTCUTS.items()}

def validate_shortcuts(jutsu, legacy_aliases, reserved_words):
    """Fail clearly if a new technique or command creates a collision."""
    if set(JUTSU_SHORTCUTS) != set(jutsu):
        raise ValueError("Every jutsu must have an explicit one-word shortcut")
    if len(SHORTCUT_JUTSU) != len(JUTSU_SHORTCUTS):
        raise ValueError("Jutsu shortcuts must be unique")
    for key, short in JUTSU_SHORTCUTS.items():
        if not short.isascii() or not short.isalnum() or len(short) < 2:
            raise ValueError(f"Invalid one-word jutsu shortcut: {short}")
        if short in reserved_words:
            raise ValueError(f"Jutsu shortcut conflicts with command: {short}")
        if legacy_aliases.get(short, key) != key or (short in jutsu and short != key):
            raise ValueError(f"Jutsu shortcut conflicts with another jutsu: {short}")
